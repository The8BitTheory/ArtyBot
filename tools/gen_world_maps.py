#!/usr/bin/env python3
"""gen_world_maps.py - generates src/world_maps.asm (world overview maps).

Usage:  python -B tools/gen_world_maps.py        (writes src/world_maps.asm)

Each world map is WMAP_COLS x WMAP_ROWS cells (2x2 characters each, the run
screen cells of the world's tileset). Map characters:
  .  path    (the only walkable cell besides the level nodes)
  ,  grass   (decoration, blocks)
  T  tree    (blocks)
  C  chest   (decoration, blocks)
  O  goal    (decoration, blocks)
  *  flowers (decoration, blocks)
  ~  water   (blocks)
  [ ]  left / right half of the gate (blocks until every level of the world is
       solved; then walkable: stepping on it leads to the next world)
  <  archway back to the previous world (always walkable). Every world except
       the first needs exactly one, the first must not have one.
  1-9        level node n of this world (drawn as goal / gold chest; walkable)
The robot starts on node 1. The script checks that every node can be reached
from node 1 over the path (gate cells count as walkable: every gate cell must
be reachable, they are the exit of the world).

Output per world NAME:
  wmap_NAME    WMAP_BYTES bytes, cells row-major, two per byte (high nibble first)
  wnodes_NAME  x, y per node (node 1 first)
  WNODES_NAME  number of nodes (= levels of the world, checked in world.asm)
"""
import os, sys
from collections import deque

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'src', 'world_maps.asm')

COLS, ROWS = 19, 10
CELL = {',': 0, 'T': 1, 'C': 2, 'O': 3, '*': 4, '~': 5, '.': 6, '[': 7, ']': 8, '<': 9}
PATH = 6

WORLDS = []

# World 1: meadow (levels 1-5). The path winds round the end of the river.
WORLDS.append(('meadow', """
TTTT[]TTTTT~~TTTTTT
T,1....*T,,~~*T,4.T
T,*T,,.,TT,~~,,T*.T
T,TT*,.,,T*~~,TT,.T
TT,....T,*~~,,T,5.T
T*,.TTT,,~~,*T,..,T
T,..,T*,~~,T,,..T,T
T,.,*T,,,~*,TT,.,*T
T,.2.........3..TTT
TTTTTTTTTTTTTTTTTTT
"""))


# World 2: winter (levels 5-9). The archway at the bottom left leads back to
# the meadow, the path winds round the frozen lake up to the gate at the top.
WORLDS.append(('winter', """
TTTTTTTTTTTTTTT[]TT
T,T,*,T,T,*,T,,..,T
T,,T,......5....,,T
T,,,T.,*,T,,,*T,,TT
T,T,,...4.....,,,,T
T,,~~~~~~~~~,.*,T,T
TT*~~~~~~~~~,3,,,*T
T,,,~~~~~~~,,.,T*,T
<..1......2...,,,,T
TTTTTTTTTTTTTTTTTTT
"""))


def parse(name, art, index):
    rows = [r for r in art.strip('\n').split('\n')]
    if len(rows) != ROWS:
        sys.exit('%s: %d rows, expected %d' % (name, len(rows), ROWS))
    cells, nodes = [], {}
    for y, r in enumerate(rows):
        if len(r) != COLS:
            sys.exit('%s row %d: %d columns, expected %d' % (name, y, len(r), COLS))
        for x, ch in enumerate(r):
            if ch.isdigit() and ch != '0':
                n = int(ch)
                if n in nodes:
                    sys.exit('%s: node %d twice' % (name, n))
                nodes[n] = (x, y)
                cells.append(PATH)
            elif ch in CELL:
                cells.append(CELL[ch])
            else:
                sys.exit('%s: unknown map character %r at %d,%d' % (name, ch, x, y))
    nback = cells.count(9)
    if nback != (0 if index == 0 else 1):
        sys.exit('%s: world %d needs %s archway(s) "<", found %d' % (
            name, index + 1, 'no' if index == 0 else 'exactly one', nback))
    if cells.count(7) != cells.count(8):
        sys.exit('%s: gate halves "[" and "]" must come in pairs' % name)
    count = len(nodes)
    if sorted(nodes) != list(range(1, count + 1)):
        sys.exit('%s: nodes must be 1..n without gaps, got %s' % (name, sorted(nodes)))
    # reachability from node 1
    walk = lambda x, y: 0 <= x < COLS and 0 <= y < ROWS and cells[y * COLS + x] in (PATH, 7, 8, 9)
    seen = {nodes[1]}
    q = deque([nodes[1]])
    while q:
        x, y = q.popleft()
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            p = (x + dx, y + dy)
            if p not in seen and walk(*p):
                seen.add(p)
                q.append(p)
    for n, p in nodes.items():
        if p not in seen:
            sys.exit('%s: node %d at %s cannot be reached from node 1' % (name, n, p))
    return cells, [nodes[n] for n in range(1, count + 1)]


def main():
    out = ['; world_maps.asm - world overview maps. GENERATED by tools/gen_world_maps.py,',
           '; edit the ASCII maps there and re-run the script instead of editing this file.',
           '; Cells: 0 grass, 1 tree, 2 chest, 3 goal, 4 flowers, 5 water, 6 path (walkable),',
           '; 7/8 gate left/right (walkable once the gate is open), 9 archway back.',
           '',
           'WMAP_COLS  = %d' % COLS,
           'WMAP_ROWS  = %d' % ROWS,
           'WMAP_BYTES = %d' % ((COLS * ROWS + 1) // 2),
           '']
    for index, (name, art) in enumerate(WORLDS):
        cells, nodes = parse(name, art, index)
        if len(cells) % 2:
            cells.append(0)
        data = [cells[i] << 4 | cells[i + 1] for i in range(0, len(cells), 2)]
        out.append('; --- %s' % name)
        for line in art.strip('\n').split('\n'):
            out.append(';   ' + line)
        out.append('wmap_%s' % name)
        for i in range(0, len(data), 16):
            out.append('        !byte ' + ','.join('$%02X' % b for b in data[i:i + 16]))
        out.append('wnodes_%s' % name)
        out.append('        !byte ' + ', '.join('%d,%d' % p for p in nodes))
        out.append('WNODES_%s = %d' % (name.upper(), len(nodes)))
        out.append('')
    with open(OUT, 'w', newline='\n') as f:
        f.write('\n'.join(out))
    print('written', os.path.normpath(OUT))


if __name__ == '__main__':
    main()
