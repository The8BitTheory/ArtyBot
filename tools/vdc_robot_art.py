def mirror(img):
    return [r[::-1] for r in img]


def robot(view, carry, step):
    if view == 'down':
        img = HEAD_DOWN + (BODY_FRONT_CARRY if carry else BODY_FRONT) + LEGS_FRONT[step]
    elif view == 'up':
        img = HEAD_UP + (BODY_FRONT_CARRY if carry else BODY_FRONT) + LEGS_FRONT[step]
    else:
        img = HEAD_RIGHT + (BODY_SIDE_CARRY if carry else BODY_SIDE) + LEGS_SIDE[step]
    return img


def images():
    out = []
    for step in (0, 1):
        for carry in (0, 1):
            r = robot('right', carry, step)
            for d, img in (('right', r), ('left', mirror(r)), ('up', robot('up', carry, step)),
                           ('down', robot('down', carry, step))):
                out.append(('robot %s%s%s' % (d, ', carrying' if carry else '', ', step' if step else ''), img, 14))
    out.append(('package (chest) carried above the head', CHEST, 12))
    out.append(('key carried above the head', KEY, 13))
    return out
