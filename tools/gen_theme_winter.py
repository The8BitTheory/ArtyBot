C['path'] = G.CELLS['path']
C['gate_l'] = G.CELLS['gate_l']
C['gate_r'] = G.CELLS['gate_r']
C['arch'] = G.CELLS['arch']
assert set(C) == set(G.CELL_ORDER), set(G.CELL_ORDER) ^ set(C)


def hexrow(b):
    return '        !byte ' + ','.join('$%02X' % x for x in b)


def main():
    o = ['; gfx_winter.asm - tileset of the winter world. GENERATED by tools/gen_theme_winter.py,',
         '; edit the ASCII art there and re-run the script instead of editing this file.',
         ';',
         '; winter_cells: RUN_CELL_TYPES cells of 4 characters (TL, TR, BL, BR), order as',
         '; gen_gfx_run.CELL_ORDER: ' + ', '.join(G.CELL_ORDER) + '.',
         '; winter_plan: the 5 planning tiles (floor, goal, package, blocker, water).',
         ';   . = $D021 black   g = $D022 snow   l = $D023 shadow   c = colour RAM',
         'winter_cells']
    for name in G.CELL_ORDER:
        art, chars = G.cell_chars(C[name])
        o.append('; --- ' + name)
        o += [';   ' + a for a in art]
        o += [hexrow(ch) for ch in chars]
    o.append('winter_cells_end')
    o.append('!if winter_cells_end - winter_cells != RUN_CELL_TYPES * 32 {')
    o.append('    !error "gfx_winter: Anzahl Zelltypen passt nicht zu RUN_CELL_TYPES"')
    o.append('}')
    o.append('winter_plan')
    for name, rows in P.WINTER_TILES:
        o.append('; ' + name)
        o += [';   ' + r for r in rows]
        o.append(hexrow(P.enc(rows)))
    o.append('winter_plan_end')
    o.append('!if winter_plan_end - winter_plan != 5 * 8 {')
    o.append('    !error "gfx_winter: 5 Plan-Kacheln erwartet"')
    o.append('}')
    o.append('')
    with open(OUT, 'w', newline='\n') as f:
        f.write('\n'.join(o))
    print('wrote', os.path.normpath(OUT))


def preview(path, bg1=1, bg2=14):
    from PIL import Image
    pal = [0x000000,0xFFFFFF,0x68372B,0x70A4B2,0x6F3D86,0x588D43,0x352879,0xB8C76F,
           0x6F4F25,0x433900,0x9A6759,0x444444,0x6C6C6C,0x9AD284,0x6C5EB5,0x959595]
    rgb = lambda i: ((pal[i] >> 16) & 255, (pal[i] >> 8) & 255, pal[i] & 255)
    bg = {'.': 0, 'g': bg1, 'l': bg2}
    # colour RAM per cell type (keep in sync with theme_winter in world.asm)
    ccol = {'grass': 6, 'tree': 5, 'chest': 2, 'goal': 3, 'flowers': 3, 'water': 6,
            'path': 2, 'gate_l': 2, 'gate_r': 2, 'arch': 3}
    n = len(G.CELL_ORDER)
    im = Image.new('RGB', (16 * n, 16 + 8 + 4), rgb(bg1))
    for i, name in enumerate(G.CELL_ORDER):
        for y, row in enumerate(C[name].strip('\n').split('\n')):
            for x, p in enumerate(row):
                col = ccol[name] if p == 'c' else bg[p]
                for k in range(2):
                    im.putpixel((i * 16 + x * 2 + k, y), rgb(col))
    pcol = [6, 3, 2, 5, 6]
    for i, (name, rows) in enumerate(P.WINTER_TILES):
        for y, row in enumerate(rows):
            for x, p in enumerate(row):
                col = pcol[i] if p == 'c' else bg[p]
                for k in range(2):
                    im.putpixel((i * 8 + x * 2 + k, 18 + y), rgb(col))
    im = im.resize((im.width * 6, im.height * 6), Image.NEAREST)
    im.save(path)
    print('preview', path)


if __name__ == '__main__':
    main()
    if '--preview' in sys.argv:
        preview(sys.argv[sys.argv.index('--preview') + 1])
